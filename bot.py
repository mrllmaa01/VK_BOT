def main_loop():
    print("🤖 Бот запущен. Ожидание сообщений через Long Poll...")
    
    # Получаем настройки Long Poll
    lp_response = api_request("groups.getLongPollServer", group_id=GROUP_ID)
    if "response" not in lp_response:
        print("❌ Не удалось получить Long Poll сервер")
        return
    
    server = lp_response["response"]["server"]
    key = lp_response["response"]["key"]
    ts = lp_response["response"]["ts"]
    print(f"✅ Long Poll подключён")
    
    while True:
        try:
            # Запрос к Long Poll серверу
            lp_request = requests.get(
                f"{server}?act=a_check&key={key}&ts={ts}&wait=25"
            ).json()
            
            if "failed" in lp_request:
                print("🔄 Обновляю Long Poll сервер...")
                lp_response = api_request("groups.getLongPollServer", group_id=GROUP_ID)
                server = lp_response["response"]["server"]
                key = lp_response["response"]["key"]
                ts = lp_response["response"]["ts"]
                continue
            
            ts = lp_request.get("ts", ts)
            
            for update in lp_request.get("updates", []):
                if update["type"] == "message_new":
                    msg = update["object"]["message"]
                    user_id = msg["from_id"]
                    text = msg["text"]
                    attachments = msg.get("attachments", [])
                    
                    # 🔥 ОБРАБОТКА ФОТО
                    if attachments and attachments[0]["type"] == "photo":
                        photo_sizes = attachments[0]["photo"]["sizes"]
                        photo_url = photo_sizes[-1]["url"]
                        
                        send_message(user_id, "🔍 Распознаю текст с фото и ищу задачу...")
                        
                        try:
                            # Скачиваем фото
                            img_data = requests.get(photo_url).content
                            with open("temp_photo.jpg", "wb") as f:
                                f.write(img_data)
                            
                            print(f"✅ Фото скачано, размер: {len(img_data)} байт")
                            
                            # Ищем по фото
                            found_ids = []
                            found_subject = None
                            for subject in ["math", "rus", "inf", "eng"]:
                                try:
                                    print(f"🔍 Ищу в предмете: {subject}")
                                    ids = sdamgia.search_by_img(subject, "temp_photo.jpg")
                                    if ids:
                                        print(f"✅ Найдено в {subject}: {ids}")
                                        found_ids.extend(ids)
                                        found_subject = subject
                                        break
                                except Exception as e:
                                    print(f"⚠️ Ошибка поиска в {subject}: {e}")
                                    continue
                            
                            if found_ids and found_subject:
                                task_id = found_ids[0]
                                send_message(user_id, f"✅ Найдено задание (ID: {task_id})! Загружаю...")
                                
                                problem = sdamgia.get_problem_by_id(found_subject, str(task_id))
                                
                                if problem:
                                    question = re.sub(r'<[^>]+>', ' ', problem["condition"]["text"])
                                    question = re.sub(r'\s+', ' ', question).strip()
                                    answer = str(problem.get("answer", "")).strip()
                                    solution = problem.get("solution", {}).get("text", "")
                                    solution = re.sub(r'<[^>]+>', ' ', solution)
                                    solution = re.sub(r'\s+', ' ', solution).strip()
                                    
                                    response = f"📸 Найденная задача:\n\n{question}\n\n✅ Ответ: {answer}"
                                    if solution:
                                        response += f"\n\n📖 Решение: {solution[:500]}..."
                                    send_message(user_id, response)
                                else:
                                    send_message(user_id, "❌ Не удалось загрузить задание.")
                            else:
                                send_message(user_id, "❌ Не удалось найти задачу по фото.")
                                
                        except Exception as e:
                            print(f"❌ Ошибка распознавания: {e}")
                            import traceback
                            traceback.print_exc()
                            send_message(user_id, f"❌ Ошибка при распознавании: {str(e)[:100]}")
                        
                        # Удаляем временный файл
                        if os.path.exists("temp_photo.jpg"):
                            os.remove("temp_photo.jpg")
                            print("🗑️ Временный файл удалён")
                    
                    else:
                        # Обычное текстовое сообщение
                        print(f"📨 {user_id}: {text[:50] if text else '[пусто]'}")
                        if text:
                            process_message(user_id, text)
                            
        except KeyboardInterrupt:
            print("\n👋 Бот остановлен.")
            break
        except Exception as e:
            print(f"⚠️ Ошибка в главном цикле: {e}")
            import traceback
            traceback.print_exc()
            time.sleep(3)

if __name__ == "__main__":
    main_loop()
