def send_message_with_image(user_id, text, image_url, keyboard=None):
    """Отправляет сообщение с картинкой как вложением"""
    
    # Сначала загружаем картинку на сервер ВК
    upload_url = api_request("photos.getMessagesUploadServer", peer_id=user_id)
    if "response" not in upload_url:
        return send_message(user_id, text, keyboard)
    
    upload_url = upload_url["response"]["upload_url"]
    
    # Скачиваем картинку и отправляем на сервер ВК
    img_data = requests.get(image_url).content
    files = {"photo": ("image.jpg", img_data, "image/jpeg")}
    upload_response = requests.post(upload_url, files=files).json()
    
    # Сохраняем фото
    save_response = api_request(
        "photos.saveMessagesPhoto",
        photo=upload_response["photo"],
        server=upload_response["server"],
        hash=upload_response["hash"]
    )
    
    if "response" in save_response:
        photo = save_response["response"][0]
        attachment = f"photo{photo['owner_id']}_{photo['id']}"
        
        params = {
            "user_id": user_id,
            "message": text[:4000],
            "attachment": attachment,
            "random_id": random.randint(1, 2**31)
        }
        if keyboard:
            params["keyboard"] = json.dumps(keyboard)
        return api_request("messages.send", **params)
    else:
        # Если не получилось — отправляем просто текст со ссылкой
        return send_message(user_id, text + f"\n\n📷 Картинка: {image_url}", keyboard)

def api_request(method, **params):
    params.update({"access_token": TOKEN, "v": API_VERSION})
    return requests.post(f"https://api.vk.com/method/{method}", data=params).json()

