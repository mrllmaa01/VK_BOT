def load_tasks_from_api(subject_key, count=20):
    """Загружает задания с коротким ответом для любого предмета"""
    api_subject = SUBJECT_MAP.get(subject_key, "math")
    
    # Правильная структура для разных предметов
    if "math" in subject_key:
        structure = {i: 3 for i in range(1, 11)}
    else:
        # Для информатики, английского - запрашиваем разные номера
        structure = {i: 4 for i in range(1, 8)}
    
    try:
        test_id = sdamgia.generate_test(api_subject, structure)
        problem_ids = sdamgia.get_test_by_id(api_subject, str(test_id))
        
        tasks = []
        for pid in problem_ids:
            if len(tasks) >= count:
                break
            
            try:
                problem = sdamgia.get_problem_by_id(api_subject, str(pid))
                
                # Очищаем условие от HTML
                question = re.sub(r'<[^>]+>', ' ', problem["condition"]["text"])
                question = re.sub(r'\s+', ' ', question).strip()
                
                # Пропускаем слишком длинные (теория)
                if len(question) > 800 or len(question) < 10:
                    continue
                
                # Проверяем ответ
                answer = str(problem.get("answer", "")).strip()
                if not answer or answer == "None" or len(answer) > 50:
                    continue
                
                # Получаем решение
                solution = problem.get("solution", {}).get("text", "")
                solution = re.sub(r'<[^>]+>', ' ', solution)
                solution = re.sub(r'\s+', ' ', solution).strip()
                if len(solution) > 600:
                    solution = solution[:600] + "..."
                
                # Картинка
                image_url = None
                if "images" in problem["condition"] and problem["condition"]["images"]:
                    image_url = problem["condition"]["images"][0]
                
                task = {
                    "q": question,
                    "ans": answer,
                    "explain": solution or "Разбор временно недоступен",
                    "topic": f"Задание {problem.get('topic', '')}",
                    "image_url": image_url
                }
                tasks.append(task)
                print(f"✅ Добавлено задание {len(tasks)}/{count} для {subject_key}")
                
            except Exception as e:
                print(f"⚠️ Ошибка при загрузке задания {pid}: {e}")
                continue
        
        print(f"✅ {subject_key}: загружено {len(tasks)} заданий")
        return tasks
        
    except Exception as e:
        print(f"❌ Ошибка загрузки {subject_key}: {e}")
        return []

def get_tasks(subject_key, count=20):
    """Универсальная загрузка заданий"""
    # Для русского используем специальную функцию
    if "rus" in subject_key:
        tasks = load_russian_tasks_from_api(count)
        if tasks:
            return tasks
    
    # Для остальных предметов
    tasks = load_tasks_from_api(subject_key, count)
    
    # Если API не вернул задания, используем резервные (захардкоженные)
    if not tasks and subject_key in ALL_TASKS:
        print(f"⚠️ API не вернул задания для {subject_key}, использую резервные")
        tasks = ALL_TASKS[subject_key].copy()
        random.shuffle(tasks)
        tasks = tasks[:count]
    
    return tasks

